_PRIORITY_ORDER = {
    AlertPriority.critical: 4,
    AlertPriority.high: 3,
    AlertPriority.medium: 2,
    AlertPriority.low: 1,
    AlertPriority.informational: 0,
}

_PRIORITY_LEVEL_TO_ALERT_PRIORITY = {
    PriorityLevel.critical: AlertPriority.critical,
    PriorityLevel.high: AlertPriority.high,
    PriorityLevel.medium: AlertPriority.medium,
    PriorityLevel.low: AlertPriority.low,
    PriorityLevel.informational: AlertPriority.informational,
}

# Per-type minimum priority -- never the whole story (see
# _combine_priority), just a floor so a type's own inherent
# significance is never fully drowned out by an asset with no business
# context set yet.
_TYPE_BASELINE_PRIORITY = {
    AlertType.new_externally_exposed_asset: AlertPriority.informational,
    AlertType.important_asset_disappeared: AlertPriority.high,
    AlertType.important_asset_reappeared: AlertPriority.medium,
    AlertType.certificate_changed: AlertPriority.low,
    AlertType.dns_infrastructure_changed: AlertPriority.low,
    AlertType.http_security_posture_changed: AlertPriority.medium,
    AlertType.infrastructure_classification_changed: AlertPriority.low,
    AlertType.high_priority_asset_detected: AlertPriority.high,
    AlertType.authorization_disabled: AlertPriority.high,
}

_HTTP_SECURITY_EVIDENCE_KEYS = ("security_headers", "cookie_security_flags")


@dataclass
class AlertCandidate:
    alert_type: AlertType
    asset_id: uuid.UUID | None
    relationship_id: uuid.UUID | None
    source_observation_id: uuid.UUID | None
    discovery_run_id: uuid.UUID | None
    priority: AlertPriority
    title: str
    description: str
    evidence: dict
    fingerprint: str


def _fingerprint(organization_id, alert_type: AlertType, *identity_parts) -> str:
    """Deterministic, semantic identity -- organization + alert_type +
    the event's own identity (an asset id, sometimes + a slot like
    hostname:port). Never a timestamp, never a database id of the
    Alert/Observation itself (Step 9.12.5's explicit requirement).
    """
    raw = "|".join([str(organization_id), alert_type.value, *(str(p) for p in identity_parts if p is not None)])
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def _build_priority_lookup(db: Session, organization_id: uuid.UUID, asset_ids: set[uuid.UUID]) -> dict[uuid.UUID, PriorityLevel]:
    """Computes PriorityLevel for every given asset in ONE batched call
    to prioritization_service.prioritize_assets (Step 9.10's already-
    proven non-N+1 entry point), not one call to the single-asset
    get_asset_priority per asset. An earlier version called
    get_asset_priority once per touched asset (and again per qualifying
    observation) -- a real N+1 a dedicated query-count test caught
    scaling linearly with candidate count. Called once per
    evaluate_run_for_alerts invocation; every classification/priority
    decision below reads from this dict, never queries prioritization
    itself again.
    """
    if not asset_ids:
        return {}
    results = prioritization_service.prioritize_assets(
        db, organization_id, asset_ids=list(asset_ids), limit=len(asset_ids)
    )
    return {result.asset.id: result.priority for result in results}


def _combine_priority(type_baseline: AlertPriority, asset_priority: PriorityLevel) -> AlertPriority:
    from_asset = _PRIORITY_LEVEL_TO_ALERT_PRIORITY[asset_priority]
    return type_baseline if _PRIORITY_ORDER[type_baseline] >= _PRIORITY_ORDER[from_asset] else from_asset


def _looked_up_priority(priority_lookup: dict, asset: Asset) -> PriorityLevel:
    return priority_lookup.get(asset.id, PriorityLevel.informational)


def _has_known_business_context(asset: Asset) -> bool:
    """Step 9.10.4's "unknown business context must remain unknown"
    applies here identically: a mere disappearance/reappearance on an
    asset nobody has classified is not, by itself, evidence that it
    matters -- important_asset_disappeared/reappeared require this
    before firing at all. Not a silent gap: still fully visible via the
    existing activity feed / asset status filter, just not promoted to
    an alert without a stated reason to care.
    """
    return asset.criticality is not None or asset.environment is not None


def _business_context_priority(asset: Asset, baseline: AlertPriority) -> AlertPriority:
    if asset.criticality == AssetCriticality.critical:
        return AlertPriority.critical
    if asset.criticality == AssetCriticality.high or asset.environment == AssetEnvironment.production:
        return AlertPriority.high
    return baseline


def _http_security_posture_differs(observation: Observation) -> bool:
    try:
        previous = json.loads(observation.previous_value or "{}")
        current = json.loads(observation.current_value or "{}")
    except (ValueError, TypeError):
        return False
    previous_subset = {
        key: discovery_normalization_service.canonicalize_for_comparison(previous.get(key))
        for key in _HTTP_SECURITY_EVIDENCE_KEYS
    }
    current_subset = {
        key: discovery_normalization_service.canonicalize_for_comparison(current.get(key))
        for key in _HTTP_SECURITY_EVIDENCE_KEYS
    }
    return previous_subset != current_subset


def _infrastructure_provider_differs(observation: Observation) -> bool:
    try:
        previous = json.loads(observation.previous_value or "{}")
        current = json.loads(observation.current_value or "{}")
    except (ValueError, TypeError):
        return False
    return previous.get("provider") != current.get("provider")


def _dns_changed(db: Session, asset: Asset, observation: Observation) -> bool:
    """dns_records_observed has no _changed counterpart (Step 9.2 never
    added comparison-based dedup for it -- unchanged, disclosed
    behavior). Mirrors prioritization_service._dns_change_recent's
    identical reasoning: compare this observation's evidence against
    the immediately preceding dns_records_observed row for the same
    asset, read-only, using the same canonicalize_for_comparison
    already trusted for this exact purpose.
    """
    previous = (
        db.query(Observation)
        .filter(
            Observation.asset_id == asset.id,
            Observation.change_type == ChangeType.dns_records_observed,
            Observation.id != observation.id,
            Observation.observed_at <= observation.observed_at,
        )
        .order_by(Observation.observed_at.desc(), Observation.id.desc())
        .first()
    )
    if previous is None:
        return False  # first-ever DNS observation for this asset -- nothing to compare against
    try:
        previous_value = discovery_normalization_service.canonicalize_for_comparison(
            json.loads(previous.current_value or "{}")
        )
        current_value = discovery_normalization_service.canonicalize_for_comparison(
            json.loads(observation.current_value or "{}")
        )
    except (ValueError, TypeError):
        return False
    return previous_value != current_value


def _classify_observation(
    db: Session, asset: Asset, observation: Observation, priority_lookup: dict
) -> AlertCandidate | None:
    change_type = observation.change_type
    org_id = asset.organization_id

    if change_type == ChangeType.asset_created:
        if asset.asset_type not in prioritization_service.INHERENTLY_EXPOSED_TYPES:
            return None
        priority = _combine_priority(
            _TYPE_BASELINE_PRIORITY[AlertType.new_externally_exposed_asset], _looked_up_priority(priority_lookup, asset)
        )
        return AlertCandidate(
            alert_type=AlertType.new_externally_exposed_asset,
            asset_id=asset.id,
            relationship_id=None,
            source_observation_id=observation.id,
            discovery_run_id=None,
            priority=priority,
            title=f"New externally exposed asset discovered: {asset.value}",
            description=(
                f"A new {asset.asset_type.value} asset ('{asset.value}') was discovered and is inherently "
                "internet-facing."
            ),
            evidence={"asset_id": str(asset.id), "asset_type": asset.asset_type.value, "value": asset.value},
            fingerprint=_fingerprint(org_id, AlertType.new_externally_exposed_asset, asset.id),
        )

    if change_type == ChangeType.asset_status_changed:
        try:
            previous_status = json.loads(observation.previous_value or "{}").get("status")
            current_status = json.loads(observation.current_value or "{}").get("status")
        except (ValueError, TypeError):
            return None

        if current_status == LifecycleStatus.disappeared.value:
            alert_type = AlertType.important_asset_disappeared
        elif current_status == LifecycleStatus.active.value and previous_status in (
            LifecycleStatus.stale.value,
            LifecycleStatus.disappeared.value,
        ):
            alert_type = AlertType.important_asset_reappeared
        else:
            return None  # e.g. first_seen -> active, a routine confirmation, not alert-worthy

        if not _has_known_business_context(asset):
            return None

        title = (
            f"Important asset disappeared: {asset.value}"
            if alert_type == AlertType.important_asset_disappeared
            else f"Previously disappeared asset reappeared: {asset.value}"
        )
        return AlertCandidate(
            alert_type=alert_type,
            asset_id=asset.id,
            relationship_id=None,
            source_observation_id=observation.id,
            discovery_run_id=None,
            priority=_business_context_priority(asset, _TYPE_BASELINE_PRIORITY[alert_type]),
            title=title,
            description=(
                f"Asset '{asset.value}' (criticality={asset.criticality.value if asset.criticality else 'unset'}, "
                f"environment={asset.environment.value if asset.environment else 'unset'}) transitioned from "
                f"'{previous_status}' to '{current_status}'."
            ),
            evidence={"previous_status": previous_status, "current_status": current_status},
            fingerprint=_fingerprint(org_id, alert_type, asset.id),
        )

    # ChangeType.asset_updated is intentionally not classified into an
    # alert here -- see AlertType's own docstring (app/core/enums.py)
    # for why: discovery never produces one (_refresh_asset's own diff
    # can only ever detect a status transition, already the dedicated
    # important_asset_reappeared type above), and the one source that
    # does -- Stage A.1's manual criticality/environment edit -- is the
    # organization's own audited classification, not an alertable change.

    if change_type == ChangeType.certificate_changed:
        priority = _combine_priority(_TYPE_BASELINE_PRIORITY[AlertType.certificate_changed], _looked_up_priority(priority_lookup, asset))
        return AlertCandidate(
            alert_type=AlertType.certificate_changed,
            asset_id=asset.id,
            relationship_id=None,
            source_observation_id=observation.id,
            discovery_run_id=None,
            priority=priority,
            title=f"TLS certificate changed for {asset.value}",
            description=(
                f"The certificate observed at '{observation.field_name}' on '{asset.value}' rotated "
                "(fingerprint changed)."
            ),
            evidence={"slot": observation.field_name},
            fingerprint=_fingerprint(org_id, AlertType.certificate_changed, asset.id, observation.field_name),
        )

    if change_type == ChangeType.http_changed:
        if not _http_security_posture_differs(observation):
            return None  # e.g. only the page title changed -- not a security-posture event
        priority = _combine_priority(
            _TYPE_BASELINE_PRIORITY[AlertType.http_security_posture_changed], _looked_up_priority(priority_lookup, asset)
        )
        return AlertCandidate(
            alert_type=AlertType.http_security_posture_changed,
            asset_id=asset.id,
            relationship_id=None,
            source_observation_id=observation.id,
            discovery_run_id=None,
            priority=priority,
            title=f"HTTP security posture changed for {asset.value}",
            description=(
                f"Security-relevant HTTP evidence (security headers or cookie flags) changed for "
                f"'{observation.field_name}' on '{asset.value}'."
            ),
            evidence={"slot": observation.field_name},
            fingerprint=_fingerprint(org_id, AlertType.http_security_posture_changed, asset.id, observation.field_name),
        )

    if change_type == ChangeType.infrastructure_changed:
        if not _infrastructure_provider_differs(observation):
            return None  # e.g. only a confidence float or PTR hostname shifted, not the classification itself
        priority = _combine_priority(
            _TYPE_BASELINE_PRIORITY[AlertType.infrastructure_classification_changed], _looked_up_priority(priority_lookup, asset)
        )
        return AlertCandidate(
            alert_type=AlertType.infrastructure_classification_changed,
            asset_id=asset.id,
            relationship_id=None,
            source_observation_id=observation.id,
            discovery_run_id=None,
            priority=priority,
            title=f"Infrastructure/cloud classification changed for {asset.value}",
            description=f"The cloud/infrastructure provider classification for '{asset.value}' changed.",
            evidence={"slot": observation.field_name},
            fingerprint=_fingerprint(
                org_id, AlertType.infrastructure_classification_changed, asset.id, observation.field_name
            ),
        )

    if change_type == ChangeType.dns_records_observed:
        if not _dns_changed(db, asset, observation):
            return None
        priority = _combine_priority(
            _TYPE_BASELINE_PRIORITY[AlertType.dns_infrastructure_changed], _looked_up_priority(priority_lookup, asset)
        )
        return AlertCandidate(
            alert_type=AlertType.dns_infrastructure_changed,
            asset_id=asset.id,
            relationship_id=None,
            source_observation_id=observation.id,
            discovery_run_id=None,
            priority=priority,
            title=f"DNS infrastructure changed for {asset.value}",
            description=f"DNS evidence for '{asset.value}' differs from the previous observation.",
            evidence={},
            fingerprint=_fingerprint(org_id, AlertType.dns_infrastructure_changed, asset.id),
        )

    return None


def _create_or_update_alert(
    db: Session, organization_id: uuid.UUID, run: DiscoveryRun | None, candidate: AlertCandidate
) -> tuple[Alert, bool]:
    """Returns (alert, created). Dedup lookup only ever matches an
    OPEN or ACKNOWLEDGED alert with the same fingerprint -- a resolved
    one is deliberately invisible to it, so the same condition
    recurring after resolution creates a genuinely new row (Step
    9.12.6's "resolved alert occurring again" requirement) rather than
    silently resurrecting or overwriting historical evidence.

    Priority is only ever raised on an update, never lowered -- a
    condition that briefly looked less severe on a later observation
    shouldn't quietly downgrade an alert a human may already be
    triaging based on its original severity.

    Both lookups below use `.with_for_update()` -- a real, necessary
    fix, not defensive decoration: an earlier version read
    `occurrence_count` in Python and wrote back `+ 1` without a row
    lock, which a genuine 3-way concurrent-write test
    (test_alert_concurrency.py) caught losing an increment (two
    updaters both reading occurrence_count=1 and both writing back 2).
    The row lock serializes concurrent updaters against the SAME
    already-existing/already-conflicting row, exactly like
    uq_alerts_org_fingerprint_open (a real Postgres constraint, not
    Python) already serializes concurrent INSERTs.
    """
    now = datetime.now(timezone.utc)

    def _apply_update(existing: Alert) -> Alert:
        existing.last_seen_at = now
        existing.occurrence_count += 1
        existing.evidence = candidate.evidence
        existing.description = candidate.description
        if _PRIORITY_ORDER[candidate.priority] > _PRIORITY_ORDER[existing.priority]:
            existing.priority = candidate.priority
        if run is not None:
            existing.discovery_run_id = run.id
        db.flush()
        return existing

    existing = (
        db.query(Alert)
        .filter(
            Alert.organization_id == organization_id,
            Alert.fingerprint == candidate.fingerprint,
            Alert.status != AlertStatus.resolved,
        )
        .with_for_update()
        .first()
    )
    if existing is not None:
        return _apply_update(existing), False

    alert = Alert(
        organization_id=organization_id,
        asset_id=candidate.asset_id,
        relationship_id=candidate.relationship_id,
        source_observation_id=candidate.source_observation_id,
        discovery_run_id=candidate.discovery_run_id or (run.id if run is not None else None),
        alert_type=candidate.alert_type,
        priority=candidate.priority,
        title=candidate.title,
        description=candidate.description,
        evidence=candidate.evidence,
        status=AlertStatus.open,
        fingerprint=candidate.fingerprint,
        first_seen_at=now,
        last_seen_at=now,
        occurrence_count=1,
    )
    try:
        # A SAVEPOINT, not a plain insert -- Step 9.12.16's genuine
        # PostgreSQL concurrency guarantee: uq_alerts_org_fingerprint_open
        # (a partial unique index, see app/models/alert.py) is what
        # actually prevents two concurrent evaluations from creating
        # duplicate open alerts for the same fingerprint, not this
        # Python code. On a conflict, only this savepoint rolls back --
        # not the whole run's transaction -- mirroring
        # discovery_normalization_service._get_or_create_asset's
        # identical pattern for the identical reason.
        with db.begin_nested():
            db.add(alert)
            db.flush()
    except IntegrityError:
        existing = (
            db.query(Alert)
            .filter(
                Alert.organization_id == organization_id,
                Alert.fingerprint == candidate.fingerprint,
                Alert.status != AlertStatus.resolved,
            )
            .with_for_update()
            .first()
        )
        assert existing is not None, "unique-constraint conflict but no matching open alert found"
        return _apply_update(existing), False

    return alert, True


def _touched_asset_ids_this_run(db: Session, run: DiscoveryRun) -> set[uuid.UUID]:
    """Every asset this run produced a real (non-rejected) result for --
    explicitly EXCLUDES `rejected` outcomes (Step 9.12.14's safety
    requirement: a scope-rejected candidate must never be treated as
    alertable), even though every current rejected-outcome call site
    already leaves resulting_asset_id unset -- this filter makes that
    guarantee explicit and independently enforced here, not merely
    inherited by accident.
    """
    return {
        row[0]
        for row in db.query(DiscoveryResult.resulting_asset_id)
        .filter(
            DiscoveryResult.discovery_run_id == run.id,
            DiscoveryResult.resulting_asset_id.isnot(None),
            DiscoveryResult.outcome != DiscoveryResultOutcome.rejected,
        )
        .all()
    }


def evaluate_run_for_alerts(
    db: Session, run: DiscoveryRun, seed_asset: Asset, *, disappeared_relationships: list | None = None
) -> list[Alert]:
    """Called once, synchronously, at the end of a successful execute_run
    (after disappearance detection). Returns the alerts that were newly
    CREATED (not merely updated) this call -- the caller uses this list
    to decide what to queue a notification for, only after its own
    commit succeeds (see discovery_service.execute_run).

    `disappeared_relationships` is detect_and_mark_disappeared_candidates's
    own return value -- needed because a disappeared candidate is, BY
    DEFINITION, absent from this run's own DiscoveryResults (that's what
    makes it disappeared), so _touched_asset_ids_this_run alone would
    never see it or the asset_status_changed Observation
    _maybe_mark_asset_disappeared wrote for it. Reappearance needs no
    equivalent: a revived asset IS re-submitted as a candidate in the
    run that revives it, so it's already covered by
    _touched_asset_ids_this_run.
    """
    touched_asset_ids = {seed_asset.id} | _touched_asset_ids_this_run(db, run)
    for relationship in disappeared_relationships or []:
        touched_asset_ids.add(relationship.source_asset_id)
        touched_asset_ids.add(relationship.target_asset_id)
    assets_by_id = {asset.id: asset for asset in db.query(Asset).filter(Asset.id.in_(touched_asset_ids)).all()}
    # ONE batched priority computation for every touched asset -- see
    # _build_priority_lookup's docstring for why this replaced a
    # per-asset call.
    priority_lookup = _build_priority_lookup(db, seed_asset.organization_id, touched_asset_ids)

    newly_created: list[Alert] = []

    observations = (
        db.query(Observation)
        .filter(Observation.asset_id.in_(touched_asset_ids), Observation.observed_at >= run.started_at)
        .all()
    )
    for observation in observations:
        asset = assets_by_id.get(observation.asset_id)
        if asset is None:
            continue
        candidate = _classify_observation(db, asset, observation, priority_lookup)
        if candidate is None:
            continue
        alert, created = _create_or_update_alert(db, asset.organization_id, run, candidate)
        if created:
            newly_created.append(alert)

    for asset_id in touched_asset_ids:
        asset = assets_by_id.get(asset_id)
        if asset is None or asset.status == LifecycleStatus.disappeared:
            continue
        level = _looked_up_priority(priority_lookup, asset)
        if level not in (PriorityLevel.high, PriorityLevel.critical):
            continue
        candidate = AlertCandidate(
            alert_type=AlertType.high_priority_asset_detected,
            asset_id=asset.id,
            relationship_id=None,
            source_observation_id=None,
            discovery_run_id=run.id,
            priority=_PRIORITY_LEVEL_TO_ALERT_PRIORITY[level],
            title=f"High-priority asset detected: {asset.value}",
            description=(
                f"Asset '{asset.value}' now evaluates to '{level.value}' priority based on exposure, business "
                "context, recent change, and connectivity."
            ),
            evidence={"asset_id": str(asset.id), "priority": level.value},
            fingerprint=_fingerprint(asset.organization_id, AlertType.high_priority_asset_detected, asset.id),
        )
        alert, created = _create_or_update_alert(db, asset.organization_id, run, candidate)
        if created:
            newly_created.append(alert)

    return newly_created


def create_authorization_disabled_alert(
    db: Session, seed_asset: Asset, schedule: DiscoverySchedule, run: DiscoveryRun | None, reason: str
) -> Alert:
    """The one alert type not sourced from an Observation -- see the
    module docstring. Called directly from
    discovery_scheduler_executor.execute_scheduled_run at the point a
    schedule auto-disables itself because authorization was revoked or
    the asset was deactivated (Step 9.11's existing behavior). Fires at
    most once per (asset, schedule) while the resulting alert stays
    open -- a schedule that keeps getting manually re-enabled and
    re-revoked updates the same alert rather than spamming a new one
    each time.
    """
    candidate = AlertCandidate(
        alert_type=AlertType.authorization_disabled,
        asset_id=seed_asset.id,
        relationship_id=None,
        source_observation_id=None,
        discovery_run_id=run.id if run is not None else None,
        priority=_TYPE_BASELINE_PRIORITY[AlertType.authorization_disabled],
        title=f"Discovery schedule disabled: authorization no longer valid for {seed_asset.value}",
        description=reason,
        evidence={
            "schedule_id": str(schedule.id),
            "provider_name": schedule.provider_name,
            "seed_asset_id": str(seed_asset.id),
        },
        fingerprint=_fingerprint(seed_asset.organization_id, AlertType.authorization_disabled, seed_asset.id, schedule.id),
    )
    alert, created = _create_or_update_alert(db, seed_asset.organization_id, None, candidate)
    db.commit()
    if created:
        queue_notifications(db, [alert])
    return alert


def queue_notifications(db: Session, alerts: list[Alert]) -> None:
    """Creates one AlertNotification per newly-created alert and hands
    each off to Celery -- a no-op entirely if email delivery isn't
    configured (Settings.alert_notification_email_enabled), so nothing
    is ever left pending indefinitely. Only ever called for NEWLY
    created alerts (never for a deduplicated update), which is what
    satisfies "repeated scheduled discovery does not spam alerts" for
    the email channel too, not just the Alert row itself.
    """
    from app.config import settings

    if not alerts or not settings.alert_notification_email_enabled:
        return

    notifications = []
    for alert in alerts:
        notification = AlertNotification(alert_id=alert.id, channel=NotificationChannel.email, status=NotificationStatus.pending)
        db.add(notification)
        notifications.append(notification)
    db.commit()

    from app.tasks.alert_notification_tasks import deliver_alert_notification_task

    for notification in notifications:
        deliver_alert_notification_task.delay(str(notification.id))


DEFAULT_ALERT_LIST_LIMIT = 50
MAX_ALERT_LIST_LIMIT = 200


def list_alerts(
    db: Session,
    organization_id: uuid.UUID,
    *,
    statuses: list[AlertStatus] | None = None,
    priorities: list[AlertPriority] | None = None,
    alert_types: list[AlertType] | None = None,
    asset_id: uuid.UUID | None = None,
    before_last_seen_at: datetime | None = None,
    before_id: uuid.UUID | None = None,
    limit: int = DEFAULT_ALERT_LIST_LIMIT,
) -> list[Alert]:
    """Ordered by (last_seen_at DESC, id DESC) -- last_seen_at alone is
    not a reliable tiebreaker (two alerts created in the same
    transaction can share an identical timestamp), matching
    graph_service.get_activity_feed's identical reasoning. Pagination
    is keyset-based (`before_last_seen_at`+`before_id`, both together,
    taken from the last item of the previous page) for the same reason
    that module chose it over OFFSET: no drift under concurrent writes.
    """
    effective_limit = min(limit, MAX_ALERT_LIST_LIMIT) if limit > 0 else DEFAULT_ALERT_LIST_LIMIT

    # joinedload(Alert.asset): Step 9.13's AlertRead.asset_value/asset_type
    # read this relationship per row -- eager-loading it here in the one
    # query is what keeps that a single JOIN instead of N lazy-loads.
    query = db.query(Alert).options(joinedload(Alert.asset)).filter(Alert.organization_id == organization_id)
    if statuses:
        query = query.filter(Alert.status.in_(statuses))
    if priorities:
        query = query.filter(Alert.priority.in_(priorities))
    if alert_types:
        query = query.filter(Alert.alert_type.in_(alert_types))
    if asset_id is not None:
        query = query.filter(Alert.asset_id == asset_id)
    if before_last_seen_at is not None and before_id is not None:
        query = query.filter(
            or_(
                Alert.last_seen_at < before_last_seen_at,
                and_(Alert.last_seen_at == before_last_seen_at, Alert.id < before_id),
            )
        )

    return query.order_by(Alert.last_seen_at.desc(), Alert.id.desc()).limit(effective_limit).all()


def acknowledge_alert(db: Session, alert: Alert, user_id: uuid.UUID) -> Alert:
    if alert.status != AlertStatus.open:
        raise ValueError(f"Alert is not open (current status: {alert.status.value})")
    alert.status = AlertStatus.acknowledged
    alert.acknowledged_at = datetime.now(timezone.utc)
    alert.acknowledged_by = user_id
    db.commit()
    db.refresh(alert)
    return alert


def resolve_alert(db: Session, alert: Alert, user_id: uuid.UUID) -> Alert:
    if alert.status == AlertStatus.resolved:
        raise ValueError("Alert is already resolved")
    alert.status = AlertStatus.resolved
    alert.resolved_at = datetime.now(timezone.utc)
    alert.resolved_by = user_id
    db.commit()
    db.refresh(alert)
    return alert
