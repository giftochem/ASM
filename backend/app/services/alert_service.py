"""Step 9.12: alert generation, deduplication, and lifecycle.

ALERT vs OBSERVATION: an Observation is "what happened" -- an
append-only fact ASM recorded (Step 8.1/9.9). An Alert is "this
deserves attention" -- a small, deterministic rule engine's judgment
that a SPECIFIC already-recorded Observation (or, for the one
exception below, a scheduler-level safety event) is significant enough
to surface. A routine unchanged observation is never even considered:
record_*_observation (discovery_normalization_service.py) only writes
an Observation when something meaningfully changed -- Step 9.9's dedup
work already did the hard part. This module's only job is deciding
which of those genuine changes also rises to "alert-worthy," using
Step 9.10's existing prioritization intelligence, never a second
scoring formula (see _build_priority_lookup/_combine_priority below --
every priority this module assigns is either taken directly from
prioritization_service.prioritize_assets or is the max of that and a
small per-type baseline).

ALERT GENERATION SAFETY (Step 9.12.14): every alert type but one
(authorization_disabled) is generated by reading Observation rows the
EXISTING normalization pipeline already wrote --
record_seed_evidence/record_certificate_observation/
record_http_observation/record_network_observation/
record_infrastructure_observation/_refresh_asset/_get_or_create_asset/
_maybe_mark_asset_disappeared, all in discovery_normalization_service.py.
Every one of those functions already enforces org-scoping,
authorization, and (for new assets) normalize_asset_value's scope/SSRF
validation before it ever writes a row -- an external SAN, an
out-of-scope redirect target, or any other scope-rejected candidate
never becomes an Observation in the first place (it becomes a
`rejected` DiscoveryResult instead, with no resulting_asset_id, which
_touched_asset_ids_this_run below explicitly excludes). This module
adds no new acceptance/validation logic of its own: it can only ever
alert on something the existing pipeline already accepted as real,
in-scope, and belonging to this organization.

evaluate_run_for_alerts() is called exactly once, synchronously, at
the very end of a successful discovery_service.execute_run -- the
identical placement as Step 9.9's disappearance detection, and for the
identical reason: a failed run never reaches this code path at all
(execute_run's _fail_run returns before either call is reached), so a
provider failure can never produce an alert, and the zero-candidates
suspicious-run guard inside detect_and_mark_disappeared_candidates
means a disappearance Observation is never even written for a
suspicious run -- this module inherits that safety for free rather
than re-implementing it. The whole call is wrapped in try/except by
the caller (execute_run) so a bug here can never turn a successful
discovery into a failed one, and notifications are only queued AFTER
execute_run's own commit succeeds (see discovery_service.execute_run)
so nothing is ever queued for an alert that might not durably exist.

WHICH OBSERVATIONS COUNT AS "FROM THIS RUN": Observation carries no
discovery_run_id (a deliberate Step 8.1 design -- see
app/models/observation.py). Since execute_run holds its own DB
transaction from the moment run.started_at is stamped (before the
provider is even called) through to commit, and normalization and
alert evaluation both run synchronously inside that same call,
"observed_at >= run.started_at" is a correct and sufficient proxy for
"written during this run" without a schema change -- no other code
path writes an Observation for the assets this run touched between
those two points in time.
"""

